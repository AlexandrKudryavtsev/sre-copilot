CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(2000),
    endpoint_url VARCHAR(2048) NOT NULL,
    endpoint_type VARCHAR(32) NOT NULL CHECK (endpoint_type IN ('PROMETHEUS', 'ACTUATOR')),
    monitoring_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    connection_status VARCHAR(32) NOT NULL DEFAULT 'UNKNOWN'
        CHECK (connection_status IN ('CONNECTED', 'UNAVAILABLE', 'UNKNOWN')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_projects_user_id ON projects(user_id);

CREATE TABLE metric_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    timestamp TIMESTAMPTZ NOT NULL,
    latency NUMERIC NOT NULL CHECK (latency >= 0),
    traffic NUMERIC NOT NULL CHECK (traffic >= 0),
    errors NUMERIC NOT NULL CHECK (errors BETWEEN 0 AND 100),
    saturation NUMERIC NOT NULL CHECK (saturation BETWEEN 0 AND 100)
);

CREATE INDEX idx_metric_snapshots_project_timestamp ON metric_snapshots(project_id, timestamp DESC);

CREATE TABLE monitoring_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    metric VARCHAR(32) NOT NULL CHECK (metric IN ('LATENCY', 'TRAFFIC', 'ERRORS', 'SATURATION')),
    operator VARCHAR(32) NOT NULL
        CHECK (operator IN ('GREATER_THAN', 'GREATER_OR_EQUAL', 'LESS_THAN', 'LESS_OR_EQUAL')),
    threshold NUMERIC NOT NULL CHECK (threshold >= 0),
    severity VARCHAR(32) NOT NULL CHECK (severity IN ('WARNING', 'CRITICAL')),
    check_interval_seconds INTEGER NOT NULL CHECK (check_interval_seconds > 0),
    consecutive_violations INTEGER NOT NULL CHECK (consecutive_violations > 0),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_monitoring_rules_project_id ON monitoring_rules(project_id);

CREATE TABLE incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    rule_id BIGINT REFERENCES monitoring_rules(id) ON DELETE SET NULL,
    title VARCHAR(255) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'RESOLVED')),
    severity VARCHAR(32) NOT NULL CHECK (severity IN ('WARNING', 'CRITICAL')),
    started_at TIMESTAMPTZ NOT NULL,
    resolved_at TIMESTAMPTZ,
    trigger_metric VARCHAR(32) NOT NULL
        CHECK (trigger_metric IN ('LATENCY', 'TRAFFIC', 'ERRORS', 'SATURATION')),
    trigger_value NUMERIC NOT NULL,
    rule_metric VARCHAR(32) NOT NULL
        CHECK (rule_metric IN ('LATENCY', 'TRAFFIC', 'ERRORS', 'SATURATION')),
    rule_operator VARCHAR(32) NOT NULL
        CHECK (rule_operator IN ('GREATER_THAN', 'GREATER_OR_EQUAL', 'LESS_THAN', 'LESS_OR_EQUAL')),
    rule_threshold NUMERIC NOT NULL,
    required_consecutive_violations INTEGER NOT NULL CHECK (required_consecutive_violations > 0),
    latency_at_detection NUMERIC NOT NULL,
    traffic_at_detection NUMERIC NOT NULL,
    errors_at_detection NUMERIC NOT NULL,
    saturation_at_detection NUMERIC NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_incidents_project_started_at ON incidents(project_id, started_at DESC);
CREATE INDEX idx_incidents_rule_id ON incidents(rule_id);
CREATE UNIQUE INDEX idx_incidents_one_open_per_rule ON incidents(rule_id) WHERE status = 'OPEN';

CREATE TABLE monitoring_rule_states (
    rule_id BIGINT PRIMARY KEY REFERENCES monitoring_rules(id) ON DELETE CASCADE,
    state VARCHAR(32) NOT NULL DEFAULT 'HEALTHY'
        CHECK (state IN ('HEALTHY', 'VIOLATING', 'INCIDENT_OPEN')),
    consecutive_violations INTEGER NOT NULL DEFAULT 0 CHECK (consecutive_violations >= 0),
    consecutive_recoveries INTEGER NOT NULL DEFAULT 0 CHECK (consecutive_recoveries >= 0),
    active_incident_id BIGINT UNIQUE REFERENCES incidents(id) ON DELETE SET NULL,
    last_checked_at TIMESTAMPTZ,
    last_violation_at TIMESTAMPTZ
);
