CREATE TABLE ai_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL UNIQUE REFERENCES incidents(id) ON DELETE CASCADE,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED', 'INSUFFICIENT_DATA')),
    probable_cause TEXT,
    evidence JSONB NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(evidence) = 'array'),
    recommendations JSONB NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(recommendations) = 'array'),
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    attempt_id UUID,
    lease_until TIMESTAMPTZ
);

CREATE INDEX idx_ai_analyses_pending ON ai_analyses(created_at, id) WHERE status = 'PENDING';

-- A transactional outbox: no HTTP calls or background tasks before the incident commits.
-- Keeps the rule engine independent of AI and covers every incident creation path.
CREATE FUNCTION enqueue_incident_ai_analysis() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO ai_analyses(incident_id) VALUES (NEW.id);
    RETURN NEW;
END;
$$;

CREATE TRIGGER incident_ai_analysis_created AFTER INSERT ON incidents
    FOR EACH ROW EXECUTE FUNCTION enqueue_incident_ai_analysis();
